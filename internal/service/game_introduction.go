func (g *Game) xianchenIntroduction(player *model.Player, command string) GameResult {
	switch command {
	case "游戏介绍":
		return gamePlayIntroduction(player)
	case "世界观", "大世界":
		return cultivationWorldIntroduction(player)
	default:
		return xianchenSystemIntroduction(player)
	}
}

