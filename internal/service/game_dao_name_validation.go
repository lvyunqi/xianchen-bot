func validateDaoName(name string) string {
	trimmed := strings.TrimSpace(name)
	if trimmed != name {
		return "道号首尾不能包含空格。"
	}
	runes := []rune(name)
	if len(runes) < 1 || len(runes) > 10 {
		return fmt.Sprintf("道号长度必须为1至10个字符，当前%d个字符。", len(runes))
	}
	hanCount, readableHan, digitCount := 0, 0, 0
	repeated := 1
	repeatedInvalid := false
	for index, value := range runes {
		switch {
		case unicode.Is(unicode.Han, value):
			hanCount++
			if strings.ContainsRune(readableDaoNameRunes, value) {
				readableHan++
			}
		case value >= 'a' && value <= 'z', value >= 'A' && value <= 'Z':
		case value >= '0' && value <= '9':
			digitCount++
		case value == '·':
		default:
			return "道号只能使用常用汉字、英文字母、少量数字和间隔号“·”，不能含表情、控制符或模板符号。"
		}
		if index > 0 && value == runes[index-1] {
			repeated++
			if repeated >= 3 {
				repeatedInvalid = true
			}
		} else {
			repeated = 1
		}
	}
	if digitCount == len(runes) || digitCount*2 > len(runes) {
		return "道号不能是纯数字，数字也不能超过名称的一半。"
	}
	if repeatedInvalid {
		return "道号不能连续堆叠三个相同字符。"
	}
	if hanCount > 0 && readableHan*2 < hanCount {
		return "道号包含过多无法辨识的生僻字或乱码，请使用至少一半常用汉字。"
	}
	return ""
}
